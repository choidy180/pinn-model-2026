// ------------------- 개별 파라미터 그룹 타입 -------------------

/** 기본 제어 정보 (QR코드, 샷카운트, 시간/위치/압력 등) */
export interface BasicInfo {
  "QR코드": string;
  "샷카운트": number;
  "전체공정시간": number;
  "사출시간": number;
  "형개시간": number;
  "계량시간": number;
  "절환위치": number;
  "최소쿠션": number;
  "계량완료위치": number;
  "최대압력": number;
  "절환압력": number;
}

/** 실린더 온도 정보 (노즐/히터존) */
export interface CylinderTemperature {
  "HN실제온도": number;
  "H1실제온도": number;
  "H2실제온도": number;
  "H3실제온도": number;
  "H4실제온도": number;
  "H5실제온도": number;
}

/** 핫러너 온도 정보 (다수 온도 센서) */
export interface HotRunnerTemperature {
  [key: string]: number; // "온도1", "온도2", ...
}

/** 사출 속도 단계별 정보 */
export interface InjectionSpeed {
  "1차사출속도": number;
  "2차사출속도": number;
  "3차사출속도": number;
  "4차사출속도": number;
  "완료사출속도": number;
}

/** 사출 거리 단계별 정보 */
export interface InjectionDistance {
  "1차사출거리": number;
  "2차사출거리": number;
  "3차사출거리": number;
  "4차사출거리": number;
  "완료사출거리": number;
}

/** 보압 정보 */
export interface HoldingPressure {
  "보압1차압력": number;
  "보압2차압력": number;
  "보압1차시간": number;
  "보압2차시간": number;
}

/** 품질 관리 (QC) 정보 */
export interface QualityControl {
  "일시": string;
  "온조기이동1": number;
  "온조기이동2": number;
  "온조기고정1": number;
  "온조기고정2": number;
  "하우징중량": number;
  "사출레진중량": number;
  "사출품중량": number;
  "비전검사NG_ROI": string | null;
  "QR스캔판정": "합격" | "불합격" | string;
  "중량검사판정": "합격" | "불합격" | string;
  "비전검사판정": "합격" | "불합격" | string;
  "전체검사판정": "합격" | "불합격" | string;
}

/** MES 생산 관련 정보 */
export interface MESProductionInfo {
  "작업지시번호": string;
  "제품코드": string;
  "목표생산량": number;
  "현재생산량": number;
  "불량수": number;
  "양품율": number;
}

/** MES 설비 관리 정보 */
export interface MESFacilityManagement {
  "가동시간": number;
  "비가동시간": number;
  "가동율": number;
  "최종점검일": string;
  "다음점검일": string;
}

/** MES 정보 그룹 */
export interface MESInfo {
  "생산정보": MESProductionInfo;
  "설비관리": MESFacilityManagement;
}


// ------------------- 장비 및 전체 레코드 타입 -------------------

/** 개별 사출 장비의 모든 파라미터 정보 */
export interface MachineParameters {
  "machineId": string;
  "machineName": string;
  "machineCode": "A" | "B" | "C" | "D" | string;
  "status": "운전중" | "대기" | "경고" | "에러" | string;

  "basicInfo": BasicInfo;
  "cylinderTemperature": CylinderTemperature;
  "hotRunnerTemperature": HotRunnerTemperature;
  "injectionSpeed": InjectionSpeed;
  "injectionDistance": InjectionDistance;
  "holdingPressure": HoldingPressure;
  "qualityControl": QualityControl;
  "mesInfo": MESInfo;
}

/** 사출 공정 전체 레코드 */
export interface InjectionProcessRecord {
  "processType": "INJECTION_MOLDING" | string;
  "processName": string;
  "timestamp": string;
  "totalMachines": number;
  
  "machines": {
    [key: string]: MachineParameters; // "A", "B", "C", "D" 키 사용
  };
}


